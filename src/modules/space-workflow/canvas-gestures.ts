/** Keep the last failed read visible while a retry is pending. A successful read clears it. */
export function planningReadPresentation(input: {
  readonly hasData: boolean;
  readonly loading: boolean;
  readonly error: string | null;
  readonly previousError: string | null;
}): { planningLoading: boolean; planningError: string | null } {
  return {
    planningLoading: input.loading && !input.hasData,
    planningError: input.error ?? (input.loading ? input.previousError : null),
  };
}

export const LONG_PRESS_MS = 450;
export const MOVE_TOLERANCE = 8;
/** Sibling canvas layers arbitrate private gestures within the current account/project only. */
export const SPACE_CANVAS_GESTURE_EVENT = "hackathon:space-canvas-gesture";

export type CanvasGestureRegion = "surface" | "content" | "safe-control" | "control" | "editor" | "document-text" | "graph-node" | "options" | "dialog";

/**
 * 独立编辑区是否可以借用外层的滚轮/拖动。
 *
 * `scrollableContent`：该编辑元素内部是否**还有可滚动的内容**。**默认 true（即保守拒绝缩放）**，
 * 只有调用方明确测出"内部没有可滚动内容"时才传 false 允许缩放。
 * - 有 → 原生滚动优先（例如内容很长的编辑框，滚轮应当滚正文，绝不抢来做缩放）；
 * - 没有 → 允许缩放。
 *
 * 为什么需要这个参数（用户 2026-10-13 报"文档组件无法放大缩小"）：
 * 空间文档卡片默认就是编辑态，正文 `textarea` **占满整张卡**（`max-height:none`、正文不滚动），
 * 原来 `editor` 区域一律拒绝缩放，于是**只要鼠标落在文档正文上，滚轮缩放就完全没反应**——
 * 那张卡几乎无处可缩。加上这个判断后，文档卡可以正常缩放，而长内容编辑框仍保留原生滚动。
 */
export function canUseCanvasGesture(region: CanvasGestureRegion, action: "drag" | "zoom", editorFocused = false, scrollableContent = true): boolean {
  if (action === "zoom" && region === "editor") return !scrollableContent;
  if (["editor", "graph-node", "options", "dialog"].includes(region)) return false;
  if (action === "drag") return region !== "control" && region !== "document-text";
  return !editorFocused || region === "surface";
}

export function movedBeforeLongPress(dx: number, dy: number): boolean {
  return Math.hypot(dx, dy) > MOVE_TOLERANCE;
}

export interface LongPressClickFence {
  readonly cardId: string;
  readonly pointerId: number;
  readonly until: number;
}

/** Ignore only the pointer click generated by a completed long press; keyboard clicks remain valid. */
export function isLongPressClick(fence: LongPressClickFence | null, click: {
  readonly cardId: string;
  readonly pointerId?: number;
  readonly detail: number;
  readonly now: number;
}): boolean {
  return !!fence && click.detail > 0 && click.cardId === fence.cardId && click.now <= fence.until
    && (click.pointerId === undefined || click.pointerId === fence.pointerId);
}

export interface CanvasPoint { readonly x: number; readonly y: number }
export interface CanvasSelectionRect extends CanvasPoint { readonly width: number; readonly height: number }

export function pointInCanvas(client: CanvasPoint, origin: CanvasPoint, scaleX = 1, scaleY = 1): CanvasPoint {
  return { x: (client.x - origin.x) / scaleX, y: (client.y - origin.y) / scaleY };
}

/** A marquee works in every drag direction and in canvas coordinates, after viewport scrolling. */
export function canvasSelectionRect(start: CanvasPoint, end: CanvasPoint): CanvasSelectionRect {
  return { x: Math.min(start.x, end.x), y: Math.min(start.y, end.y), width: Math.abs(end.x - start.x), height: Math.abs(end.y - start.y) };
}

/** The caller supplies measured, scaled outer bounds; touching a visible component selects it. */
export function intersectingCanvasItems(items: readonly (CanvasSelectionRect & { readonly instanceId: string })[], area: CanvasSelectionRect): string[] {
  if (area.width === 0 || area.height === 0) return [];
  return items.filter(item => item.x <= area.x + area.width && item.x + item.width >= area.x
    && item.y <= area.y + area.height && item.y + item.height >= area.y).map(item => item.instanceId);
}

/** Clamp the whole group at the top/left boundary, never clamp its members independently. */
export function translateCanvasGroup<T extends CanvasPoint>(items: readonly T[], dx: number, dy: number): T[] {
  if (!items.length) return [];
  if (!Number.isFinite(dx) || !Number.isFinite(dy)) return [...items];
  const x = Math.max(-Math.min(...items.map(item => item.x)), Math.round(dx));
  const y = Math.max(-Math.min(...items.map(item => item.y)), Math.round(dy));
  return items.map(item => ({ ...item, x: item.x + x, y: item.y + y }));
}

/** Scale positions and sizes around one stable top-left anchor. Every member
 * shares the same multiplier, including when one member reaches a limit. The
 * persistence adapter must retain fractional positions/scales, not round each
 * member independently to pixels or percentages. */
export function scaleCanvasGroup<T extends CanvasPoint & { readonly scale: number }>(
  items: readonly T[], requestedFactor: number, minScale = 0.5, maxScale = 2,
): { items: readonly T[]; factor: number } {
  const unchanged = { items, factor: 1 };
  if (!items.length || !Number.isFinite(requestedFactor) || requestedFactor <= 0
    || !Number.isFinite(minScale) || !Number.isFinite(maxScale) || minScale <= 0 || maxScale < minScale
    || items.some(item => !Number.isFinite(item.x) || !Number.isFinite(item.y) || item.x < 0 || item.y < 0
      || !Number.isFinite(item.scale) || item.scale < minScale || item.scale > maxScale)) return unchanged;
  const lower = Math.max(...items.map(item => minScale / item.scale));
  const upper = Math.min(...items.map(item => maxScale / item.scale));
  const factor = Math.max(lower, Math.min(upper, requestedFactor));
  if (Math.abs(factor - 1) < 1e-12) return unchanged;
  const anchor = { x: Math.min(...items.map(item => item.x)), y: Math.min(...items.map(item => item.y)) };
  const next = items.map(item => ({ ...item,
    x: anchor.x + (item.x - anchor.x) * factor,
    y: anchor.y + (item.y - anchor.y) * factor,
    // Clamp only floating-point boundary noise after calculating the common factor.
    scale: Math.max(minScale, Math.min(maxScale, item.scale * factor)),
  }));
  return next.some(item => !Number.isFinite(item.x) || !Number.isFinite(item.y) || item.x > Number.MAX_SAFE_INTEGER || item.y > Number.MAX_SAFE_INTEGER)
    ? unchanged : { items: next, factor };
}
