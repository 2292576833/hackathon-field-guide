test("an unauthenticated invite preserves its destination through login and joins only after explicit acceptance", async ({ page, browser, workspace }) => {
  const identity = Date.now();
  await browserLogin(page, workspace, `qa-inviter-${identity}@example.test`);
  const created = await browserRequest(workspace, page, "projects", "POST", { name: `邀请验收项目 ${identity}`, timezone: "Asia/Shanghai" });
  expect(created.ok).toBeTruthy();
  const project = (await created.json()).data;
  const invited = await browserRequest(workspace, page, `projects/${project.id}/invitations`, "POST", { expectedRevision: project.revision, role: "member" });
  expect(invited.ok).toBeTruthy();
  const invitation = (await invited.json()).data;
  const joinPath = `/app/join/${invitation.token}`;
  const context = await workspace.attach(await browser.newContext({ baseURL: new URL(page.url()).origin }));
  try {
    await context.addInitScript(() => localStorage.setItem("hackathon-navigator-intro-2026-10-08-v1", "seen"));
    const member = await context.newPage();
    await member.goto(joinPath);
    const loginLink = member.getByRole("link", { name: "登录后继续核对邀请", exact: true });
    await expect(loginLink).toHaveAttribute("href", `/login?returnTo=${encodeURIComponent(joinPath)}`);
    await loginLink.click();
    await browserLogin(member, workspace, `qa-invitee-${identity}@example.test`, joinPath);
    expect((await browserRequest(workspace, member, `projects/${project.id}`)).status).toBe(404);
    await member.getByLabel("我已核对目标与角色，明确接受这条邀请。", { exact: true }).check();
    await member.getByRole("button", { name: "加入团队空间", exact: true }).click();
    await expect(member.getByRole("link", { name: "进入团队空间", exact: true })).toBeVisible();
    expect((await browserRequest(workspace, member, `projects/${project.id}`)).ok).toBeTruthy();
  } finally { await context.close(); }
});
